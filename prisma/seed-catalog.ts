async function seedKind(kind: CatalogKind, cats: SeedCat[]) {
  for (let ci = 0; ci < cats.length; ci++) {
    const c = cats[ci];
    const created = await prisma.catalogCategory.create({
      data: { kind, name: c.name, note: c.note ?? null, sortOrder: ci },
    });
    await prisma.catalogItem.createMany({
      data: c.items.map((it, ii) => ({
        categoryId: created.id,
        name: it.name,
        description: it.description ?? null,
        price: it.price ?? null,
        badge: it.badge ?? null,
        sortOrder: ii,
      })),
    });
  }
}

async function main() {
  console.log("🧹 Очистка каталогу...");
  await prisma.catalogItem.deleteMany();
  await prisma.catalogCategory.deleteMany();

  console.log("📦 Товари...");
  await seedKind("PRODUCT", PRODUCTS);

  console.log("🎓 Послуги...");
  await seedKind("SERVICE", SERVICES);

  const [p, s] = await Promise.all([
    prisma.catalogItem.count({ where: { category: { kind: "PRODUCT" } } }),
    prisma.catalogItem.count({ where: { category: { kind: "SERVICE" } } }),
  ]);
  console.log(`✅ Готово. Товарів: ${p}, послуг: ${s}`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
